/**
 * Sync package brand faces into public/ for DeferredFonts.
 *
 * Lumi skips `@cyberskill/design/tokens/fonts.css` on the critical path
 * (font-display:swap would fight the CLS contract). This script mirrors a
 * Lumi-needed subset of package @font-face rules under public/fonts/ds/ and
 * writes public/fonts/brand-fonts.css with font-display:optional + public URLs.
 *
 * Subset (keeps public/ under asset budget; mono/italics unused on Lumi):
 *   - Be Vietnam Pro normal 400/500/600/700 × latin · latin-ext · vietnamese
 *   - Space Grotesk variable × latin · latin-ext · vietnamese
 *
 * Run: node scripts/sync-ds-fonts.mjs  (also via postinstall)
 * Exit 0 = wrote files, 1 = package missing / malformed.
 */
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pkgRoot = resolve(root, "node_modules/@cyberskill/design");
const fontsCssPath = resolve(pkgRoot, "tokens/fonts.css");
const pkgFontsDir = resolve(pkgRoot, "fonts");
const outDir = resolve(root, "public/fonts/ds");
const outCss = resolve(root, "public/fonts/brand-fonts.css");

/** Keep faces Lumi actually paints; drop mono + italics + thin/extrabold. */
function keepFace(block) {
  if (/font-family:\s*'JetBrains Mono'/i.test(block)) return false;
  if (/font-style:\s*italic/i.test(block)) return false;
  if (/font-family:\s*'Space Grotesk'/i.test(block)) return true;
  if (!/font-family:\s*'Be Vietnam Pro'/i.test(block)) return false;
  const weight = block.match(/font-weight:\s*(\d+)/i);
  if (!weight) return false;
  const w = Number(weight[1]);
  return w === 400 || w === 500 || w === 600 || w === 700;
}

let src;
try {
  src = readFileSync(fontsCssPath, "utf8");
} catch {
  console.error(
    "FAIL — `@cyberskill/design` not installed (missing tokens/fonts.css)",
  );
  process.exit(1);
}
if (!src.includes("@font-face") || !src.includes("Space Grotesk")) {
  console.error("FAIL — package tokens/fonts.css missing expected faces");
  process.exit(1);
}

const blocks = src.match(/@font-face\{[^}]+\}/g) || [];
const kept = blocks.filter(keepFace);
if (kept.length < 10) {
  console.error(`FAIL — expected ≥10 Lumi faces, got ${kept.length}`);
  process.exit(1);
}

const needed = new Set();
for (const block of kept) {
  for (const m of block.matchAll(/url\("\.\.\/fonts\/([^"]+)"\)/g)) {
    needed.add(m[1]);
  }
}
if (!needed.size) {
  console.error("FAIL — no ../fonts/*.woff2 urls in kept faces");
  process.exit(1);
}

for (const file of needed) {
  if (!existsSync(join(pkgFontsDir, file))) {
    console.error(`FAIL — package font asset missing: ${file}`);
    process.exit(1);
  }
}

mkdirSync(outDir, { recursive: true });
for (const name of readdirSync(outDir)) {
  rmSync(join(outDir, name), { force: true, recursive: true });
}

for (const file of needed) {
  copyFileSync(join(pkgFontsDir, file), join(outDir, file));
}

const body = kept
  .map((block) =>
    block
      .replace(/font-display:\s*swap/gi, "font-display:optional")
      .replace(/url\("\.\.\/fonts\/([^"]+)"\)/g, 'url("/fonts/ds/$1")'),
  )
  .join("\n");

if (/font-display:\s*swap/i.test(body)) {
  console.error("FAIL — swap display policy leaked into brand-fonts.css");
  process.exit(1);
}
if (!/font-display:\s*optional/i.test(body)) {
  console.error("FAIL — brand-fonts.css missing font-display:optional");
  process.exit(1);
}
if (!/Space Grotesk/.test(body) || !/Be Vietnam Pro/.test(body)) {
  console.error("FAIL — brand-fonts.css missing required families");
  process.exit(1);
}

const banner = `/* GENERATED by scripts/sync-ds-fonts.mjs — do not edit by hand.
 * Source subset of @cyberskill/design/tokens/fonts.css (package pin in package.json).
 * font-display rewritten swap → optional for Lumi DeferredFonts / CLS contract.
 * Includes Be Vietnam Pro 400–700 + Space Grotesk variable (no mono/italics).
 * Re-run: npm run sync:ds:fonts (also postinstall).
 */
`;

writeFileSync(outCss, banner + body + "\n");
console.log(
  `PASS — synced ${needed.size} package faces (${kept.length} @font-face) → public/fonts/ds/ + brand-fonts.css (optional)`,
);
